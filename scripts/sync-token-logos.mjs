// Copies the logos of tokens in the most active Robinhood Chain pools and of the official Stock Tokens into public/tokens/<address>.webp (64 px)
// and lists them in src/config/token-logos.generated.json. Run by hand when the pool list has moved on:
//   node scripts/sync-token-logos.mjs
// The site never loads token images from a third party at runtime: a token without a local logo gets a drawn
// glyph instead. Sources: the image URL GeckoTerminal lists for each token (usually the CoinGecko CDN).
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const PAGES = [1, 2, 3];
const OUT_DIR = new URL("../public/tokens/", import.meta.url);
const LIST = new URL("../src/config/token-logos.generated.json", import.meta.url);
const UA = { "user-agent": "Mozilla/5.0 (compatible; logo sync)", accept: "application/json" };
mkdirSync(OUT_DIR, { recursive: true });

let known = [];
try {
  known = JSON.parse(readFileSync(LIST, "utf8")).addresses ?? [];
} catch {
  // first run
}
const have = new Set(known);
const tokens = new Map();
for (const page of PAGES) {
  const res = await fetch(`https://api.geckoterminal.com/api/v2/networks/robinhood/pools?page=${page}&sort=h24_volume_usd_desc&include=base_token,quote_token`, { headers: UA });
  if (!res.ok) {
    console.log(`page ${page}: HTTP ${res.status}, stopping`);
    break;
  }
  const body = await res.json();
  for (const t of body.included ?? []) {
    if (t.type !== "token") continue;
    const a = String(t.attributes?.address ?? "").toLowerCase();
    const url = t.attributes?.image_url;
    if (/^0x[0-9a-f]{40}$/.test(a) && typeof url === "string" && /^https:\/\//.test(url) && !/missing/.test(url)) tokens.set(a, url);
  }
  await new Promise((r) => setTimeout(r, 2500));
}
// Official Stock Tokens (src/config/stocks.generated.json) by address, 30 per call.
const STOCKS = JSON.parse(readFileSync(new URL("../src/config/stocks.generated.json", import.meta.url), "utf8")).stocks.map((s) => s.token.toLowerCase());
for (let i = 0; i < STOCKS.length; i += 30) {
  const res = await fetch(`https://api.geckoterminal.com/api/v2/networks/robinhood/tokens/multi/${STOCKS.slice(i, i + 30).join(",")}`, { headers: UA });
  if (!res.ok) {
    console.log(`stocks ${i}: HTTP ${res.status}`);
    continue;
  }
  for (const t of (await res.json()).data ?? []) {
    const a = String(t.attributes?.address ?? "").toLowerCase();
    const url = t.attributes?.image_url;
    if (/^0x[0-9a-f]{40}$/.test(a) && typeof url === "string" && /^https:\/\//.test(url) && !/missing/.test(url)) tokens.set(a, url);
  }
  await new Promise((r) => setTimeout(r, 2500));
}
let added = 0;
for (const [address, url] of tokens) {
  const file = new URL(`${address}.webp`, OUT_DIR);
  if (have.has(address) && existsSync(file)) continue;
  try {
    const res = await fetch(url, { headers: { "user-agent": UA["user-agent"] } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > 3_000_000) throw new Error("too large");
    await sharp(buf).resize(64, 64, { fit: "cover" }).webp({ quality: 82 }).toFile(fileURLToPath(file));
    have.add(address);
    added++;
  } catch (e) {
    console.log(`skip ${address}: ${e.message}`);
  }
}
const addresses = [...have].filter((a) => existsSync(new URL(`${a}.webp`, OUT_DIR))).sort();
writeFileSync(LIST, JSON.stringify({ note: "Generated by scripts/sync-token-logos.mjs", addresses }, null, 1) + "\n");
console.log(`${addresses.length} logos (${added} new)`);
